package com.mattricks.verified.auth

import android.app.Activity
import android.content.Context
import android.util.Log
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.Firebase
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider
import com.google.firebase.auth.auth
import com.google.firebase.auth.userProfileChangeRequest
import com.mattricks.verified.BuildConfig
import com.mattricks.verified.data.Store
import kotlinx.coroutines.channels.awaitClose
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.callbackFlow
import kotlinx.coroutines.tasks.await
import org.json.JSONObject

object Auth {
    private const val TAG = "VerifiedAuth"

    fun user(): Flow<FirebaseUser?> = callbackFlow {
        val l = com.google.firebase.auth.FirebaseAuth.AuthStateListener { trySend(it.currentUser) }
        Firebase.auth.addAuthStateListener(l)
        awaitClose { Firebase.auth.removeAuthStateListener(l) }
    }

    /**
     * Server (web) OAuth client id generated by the google-services plugin from oauth_client type 3.
     * It is absent until the Google provider is enabled in Firebase Auth and google-services.json re-downloaded.
     */
    fun webClientId(ctx: Context): String? {
        val res = ctx.resources.getIdentifier("default_web_client_id", "string", ctx.packageName)
        return if (res != 0) ctx.getString(res).takeIf { it.isNotBlank() } else null
    }

    /** Google sign-in via Credential Manager + GetGoogleIdOption. Returns an error message or null on success. */
    suspend fun signInWithGoogle(activity: Activity): String? {
        val clientId = webClientId(activity)
            ?: return "Google sign-in isn't configured yet: enable the Google provider in Firebase Auth and re-download google-services.json."
        return try {
            val option = GetGoogleIdOption.Builder()
                .setFilterByAuthorizedAccounts(false)
                .setServerClientId(clientId)
                .setAutoSelectEnabled(true)
                .build()
            val result = CredentialManager.create(activity)
                .getCredential(activity, GetCredentialRequest.Builder().addCredentialOption(option).build())
            val cred = result.credential
            if (cred !is CustomCredential || cred.type != GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                return "Unexpected credential type"
            }
            val idToken = GoogleIdTokenCredential.createFrom(cred.data).idToken
            val user = Firebase.auth.signInWithCredential(GoogleAuthProvider.getCredential(idToken, null)).await().user
            user?.let { Store.upsertUser(it) }
            null
        } catch (e: GetCredentialCancellationException) {
            "Sign-in cancelled"
        } catch (e: Exception) {
            Log.e(TAG, "google sign-in", e)
            e.message ?: e.javaClass.simpleName
        }
    }

    /**
     * Emulator only: the Auth emulator accepts an unsigned JSON id_token for the google.com provider,
     * so we can create a "Google" user without a real OAuth client.
     */
    suspend fun signInEmulatorTestUser(name: String = "Android Tester"): String? {
        if (!BuildConfig.USE_EMULATOR) return "Test sign-in is only available in emulator mode"
        return try {
            val claims = JSONObject()
                .put("sub", "android-tester")
                .put("email", "android.tester@example.com")
                .put("email_verified", true)
                .put("name", name)
            val user = try {
                Firebase.auth.signInWithCredential(GoogleAuthProvider.getCredential(claims.toString(), null)).await().user
            } catch (e: Exception) {
                Log.w(TAG, "fake google credential rejected, falling back to anonymous", e)
                Firebase.auth.signInAnonymously().await().user?.also {
                    it.updateProfile(userProfileChangeRequest { displayName = name }).await()
                }
            }
            user?.let { Store.upsertUser(it) }
            null
        } catch (e: Exception) {
            Log.e(TAG, "emulator sign-in", e)
            e.message ?: e.javaClass.simpleName
        }
    }

    suspend fun signOut(ctx: Context) {
        Firebase.auth.signOut()
        runCatching { CredentialManager.create(ctx).clearCredentialState(androidx.credentials.ClearCredentialStateRequest()) }
    }
}
